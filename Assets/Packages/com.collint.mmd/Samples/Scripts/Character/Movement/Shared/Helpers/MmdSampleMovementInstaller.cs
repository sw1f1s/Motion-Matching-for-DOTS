using ColInt.MMD.Playback.Systems;
using ColInt.MMD.Samples.Character.Movement.CrouchState.Systems;
using ColInt.MMD.Samples.Character.Movement.Facing.Systems;
using ColInt.MMD.Samples.Character.Movement.FallState.Systems;
using ColInt.MMD.Samples.Character.Movement.JumpState.Systems;
using ColInt.MMD.Samples.Character.Movement.LandingState.Systems;
using ColInt.MMD.Samples.Character.Movement.LocomotionState.Systems;
using ColInt.MMD.Samples.Character.Movement.Shared.Systems;
using ColInt.MMD.Samples.Character.Movement.Trajectory.Systems;
using ColInt.MMD.Samples.Character.Movement.TraversalState.Systems;
using Unity.Entities;

namespace ColInt.MMD.Samples.Character.Movement.Shared.Helpers {
	public static class MmdSampleMovementInstaller {
		public static void Install(World world, FixedStepSimulationSystemGroup fixedGroup) {
			var simulation = world.GetExistingSystemManaged<MmdSimulationGroup>();
			var entry = world.GetOrCreateSystemManaged<MmdSampleActionEntryGroup>();
			entry.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleJumpTakeoffSystem>());
			entry.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleTraversalEntrySystem>());
			simulation.AddSystemToUpdateList(entry);
			var query = world.GetOrCreateSystemManaged<MmdSampleSearchQueryGroup>();
			query.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleTrajectorySystem>());
			query.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSamplePoseQuerySystem>());
			simulation.AddSystemToUpdateList(query);
			var feedback = world.GetOrCreateSystemManaged<MmdSampleMotionFeedbackGroup>();
			feedback.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSamplePhysicsMotionFeedbackSystem>());
			simulation.AddSystemToUpdateList(feedback);
			var traversalTrajectory = world.GetOrCreateSystemManaged<MmdSampleTraversalTrajectoryGroup>();
			traversalTrajectory.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleTraversalTrajectorySystem>());
			simulation.AddSystemToUpdateList(traversalTrajectory);
			var selection = world.GetOrCreateSystemManaged<MmdSampleLocomotionSelectionGroup>();
			selection.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleLocomotionSelectionSystem>());
			simulation.AddSystemToUpdateList(selection);
			var facing = world.GetOrCreateSystemManaged<MmdSampleFacingGroup>();
			facing.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleFacingSystem>());
			simulation.AddSystemToUpdateList(facing);
			var states = world.GetOrCreateSystemManaged<MmdSampleStateGroup>();
			var ground = world.GetOrCreateSystemManaged<MmdSampleStateGroundGroup>();
			var intent = world.GetOrCreateSystemManaged<MmdSampleJumpIntentGroup>();
			intent.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleJumpIntentSystem>());
			var requests = world.GetOrCreateSystemManaged<MmdSampleStateRequestGroup>();
			var updates = world.GetOrCreateSystemManaged<MmdSampleStateUpdateGroup>();
			var begin = world.GetOrCreateSystemManaged<MmdSampleStateBeginGroup>();
			var finish = world.GetOrCreateSystemManaged<MmdSampleStateFinishGroup>();
			var commit = world.GetOrCreateSystemManaged<MmdSampleStateCommitGroup>();
			var start = world.GetOrCreateSystemManaged<MmdSampleStateStartGroup>();
			var cleanup = world.GetOrCreateSystemManaged<MmdSampleStateCleanupGroup>();
			var policy = world.GetOrCreateSystemManaged<MmdSampleStatePolicyGroup>();
			ground.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleGroundSystem>());
			requests.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleTraversalRequestSystem>());
			requests.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCrouchRequestSystem>());
			requests.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleJumpRequestSystem>());
			requests.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleFallRequestSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleMantleUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleClimbUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleVaultUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleHurdleUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchMantleUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchCliffUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchVaultUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchHurdleUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCrouchEnterUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCrouchUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCrouchExitUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleLocomotionUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleJumpUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleFallUpdateSystem>());
			updates.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleLandingUpdateSystem>());
			begin.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleStateBeginSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleMantleFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleClimbFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleVaultFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleHurdleFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchMantleFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchCliffFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchVaultFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchHurdleFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCrouchEnterFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCrouchFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCrouchExitFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleLocomotionFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleJumpFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleFallFinishSystem>());
			finish.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleLandingFinishSystem>());
			commit.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleStateCommitSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleMantleStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleClimbStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleVaultStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleHurdleStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchMantleStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchCliffStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchVaultStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCatchHurdleStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCrouchEnterStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCrouchStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCrouchExitStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleLocomotionStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleJumpStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleFallStartSystem>());
			start.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleLandingStartSystem>());
			cleanup.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleStateCleanupSystem>());
			policy.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleCapsulePolicySystem>());
			policy.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleGroundPolicySystem>());
			states.AddSystemToUpdateList(ground);
			states.AddSystemToUpdateList(intent);
			states.AddSystemToUpdateList(requests);
			states.AddSystemToUpdateList(updates);
			states.AddSystemToUpdateList(begin);
			states.AddSystemToUpdateList(finish);
			states.AddSystemToUpdateList(commit);
			states.AddSystemToUpdateList(start);
			states.AddSystemToUpdateList(cleanup);
			states.AddSystemToUpdateList(policy);
			states.SortSystems();
			simulation.AddSystemToUpdateList(states);
			var movement = world.GetOrCreateSystemManaged<MmdSampleMovementGroup>();
			movement.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleMovementSystem>());
			fixedGroup.AddSystemToUpdateList(movement);
			var traversalMotion = world.GetOrCreateSystemManaged<MmdSampleTraversalMotionGroup>();
			traversalMotion.AddSystemToUpdateList(world.GetOrCreateSystem<MmdSampleTraversalMotionSystem>());
			fixedGroup.AddSystemToUpdateList(traversalMotion);
			fixedGroup.SortSystems();
		}
	}
}
